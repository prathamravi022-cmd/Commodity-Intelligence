"""Per-page canvas backgrounds — one scene for every screen in the workspace.

The dashboard's canvas is not one wallpaper repeated nine times. Each page opens
on its own composition: a hand-built vector scene (``app/static/backgrounds``,
generated by ``tools/make_backgrounds.py``), an optional licensed bullion
photograph underneath it, a gold light source aimed at a page-specific corner,
and a navy wash calibrated per page so figures stay readable over the picture.

The rules are scoped with ``:has()`` to a marker div that the page emits:

    <div class="page-scope" data-bg="spread-analytics"></div>

so the canvas changes when the reader navigates, and the stylesheet itself never
has to be re-injected per page. A browser without ``:has()`` support simply keeps
the default photographic canvas from ``app.theme`` — the page is still readable,
it is only less specifically lit.

Everything here is static and local: no scene is fetched from the network at
runtime, and no scene contains a number, a price or a result. The shapes are
atmosphere, not data.
"""

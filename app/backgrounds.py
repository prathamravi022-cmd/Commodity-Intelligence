#: CSS class on the marker div, and the attribute carrying the page key.
MARKER_CLASS = "page-scope"


def slug_for(title: str) -> str:
    """Stable key for a page title (``"Spread Analytics"`` → ``"spread-analytics"``)."""
    return title.strip().lower().replace(" ", "-")


def config_for(title: str) -> dict | None:
    """Background configuration for a page, or ``None`` when it has none."""
    return PAGE_BACKGROUNDS.get(title)


def scene_url(name: str) -> str:
    """Public URL of a generated scene (served by Streamlit's static server)."""
    return f"{SCENE_PREFIX}/{name}"


def _scrim(alpha: float) -> str:
    """Navy wash that holds the picture down to atmosphere at the page's depth."""
    top = min(alpha, 0.99)
    middle = min(alpha + 0.04, 0.995)
    bottom = min(alpha + 0.07, 0.998)
    return (f"linear-gradient(180deg, rgba(7,11,20,{top:.2f}) 0%, "
            f"rgba(7,11,20,{middle:.2f}) 45%, "
            f"rgba(5,8,15,{bottom:.2f}) 100%)")


def layers(title: str) -> tuple[list[str], list[str], list[str]]:
    """``(images, sizes, positions)`` for a page's canvas stack, top layer first.

    The gold light and the cool counter-light come from the theme's vocabulary so
    the page canvas and the panels above it are lit by the same two sources.
    """
    cfg = config_for(title)
    if cfg is None:
        return [], [], []

    glow_x, glow_y = cfg["glow"]
    images = [
        (f"radial-gradient(120% 80% at {glow_x} {glow_y}, "
         f"rgba(232,205,138,{cfg['glow_alpha']:.2f}), "
         f"rgba(232,205,138,0) 60%)"),
        "radial-gradient(90% 64% at 2% 106%, rgba(143,184,236,0.09), "
        "rgba(143,184,236,0) 62%)",
        f"url({scene_url(cfg['scene'])})",
        _scrim(cfg["scrim"]),
    ]
    positions = [f"{glow_x} {glow_y}", "2% 106%", cfg["scene_position"],
                 "center top"]
    sizes = ["cover", "cover", "cover", "cover"]

    photo = cfg["photo"]
    if photo:
        url = artwork.background_url(photo, artwork.PHOTOS[photo]["widths"][0])
        if url:
            images.append(f"url({url})")
            positions.append(cfg["focal"])
            sizes.append("cover")
    return images, sizes, positions


def canvas_css(title: str) -> str:
    """One scoped ``.stApp`` override for a page canvas."""
    images, sizes, positions = layers(title)
    if not images:
        return ""
    key = slug_for(title)
    return (
        f'/* {title} — {config_for(title)["role"]} */\n'
        f'.stApp:has(.{MARKER_CLASS}[data-bg="{key}"]) {{\n'
        f"    background-image: {', '.join(images)};\n"
        f"    background-size: {', '.join(sizes)};\n"
        f"    background-position: {', '.join(positions)};\n"
        f"    background-repeat: {', '.join(['no-repeat'] * len(images))};\n"
        f"    background-attachment: {', '.join(['fixed'] * len(images))};\n"
        f"}}"
    )


def scoped_css() -> str:
    """Every page rule, in navigation order."""
    from app.components import NAV_PAGES  # local: components imports the theme

    blocks = [canvas_css(page["title"]) for page in NAV_PAGES]
    return "\n".join(block for block in blocks if block)


def marker(title: str) -> str:
    """The empty div the scoped rules look for (hidden; carries no content)."""
    if config_for(title) is None:
        return ""
    return f'<div class="{MARKER_CLASS}" data-bg="{slug_for(title)}"></div>'


def apply_page_background(title: str) -> None:
    """Select this page's canvas. Called once per page by ``page_header``."""
    html = marker(title)
    if html:
        st.markdown(html, unsafe_allow_html=True)
